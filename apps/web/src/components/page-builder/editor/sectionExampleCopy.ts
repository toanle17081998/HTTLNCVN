export function sectionExampleCopy(locale: Locale, text: string) {
  return locale === "vi" && Object.hasOwn(vietnameseExampleCopy, text) ? vietnameseExampleCopy[text] : text;
}

// Apply only to built-in block defaults when creating a new section.
export function localizeSectionExampleProps<Props extends object>(props: Props, locale: Locale): Props {
  if (locale !== "vi") return props;

  function translate(value: unknown): unknown {
    if (typeof value === "string") return sectionExampleCopy(locale, value);
    if (Array.isArray(value)) return value.map(translate);
    if (value && typeof value === "object") {
      return Object.fromEntries(Object.entries(value).map(([key, entry]) => [key, translate(entry)]));
    }
    return value;
  }

  return translate(props) as Props;
}
