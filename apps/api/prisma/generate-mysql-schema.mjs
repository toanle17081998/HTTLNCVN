import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const prismaDirectory = dirname(fileURLToPath(import.meta.url));
const sourcePath = join(prismaDirectory, "schema.prisma");
const targetPath = join(prismaDirectory, "schema.mysql.prisma");
const source = await readFile(sourcePath, "utf8");

const mysqlSchema = source
  .replace('provider = "postgresql"', 'provider = "mysql"')
  .replaceAll('@default(dbgenerated("gen_random_uuid()"))', '@default(uuid())')
  .replaceAll('@db.Uuid', '@db.Char(36)')
  .replaceAll('@db.Timestamptz', '@db.DateTime(3)')
  .replace('skills         String[] @default([])', 'skills         Json');

await writeFile(
  targetPath,
  `// Generated by prisma/generate-mysql-schema.mjs. Do not edit directly.\n${mysqlSchema}`,
  "utf8",
);

console.log(targetPath);

